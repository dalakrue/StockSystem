def _pip_of(sym):
    return 0.01 if "JPY" in sym else 0.0001


def _pos32(h, l, c, idx):
    """Close position in the last-32-M15-bar range
    [0, 1]: (entry close - lowest low of bars
    idx-31..idx) / (highest high - lowest low of
    the same bars); None when unavailable."""
    if idx < 31:
        return None
    hh = float(np.max(h[idx - 31:idx + 1]))
    ll = float(np.min(l[idx - 31:idx + 1]))
    if hh <= ll:
        return None
    return (float(c[idx]) - ll) / (hh - ll)


def _atr14_pips(h, l, c, idx, sym):
    """ATR14 in pips at bar idx, build_universe_
    jul's atr14 verbatim: mean true range over
    bars idx-13..idx against the closes of bars
    idx-14..idx-1, divided by the pip size."""
    hh = h[idx - 13:idx + 1]
    ll = l[idx - 13:idx + 1]
    pc = c[idx - 14:idx]
    tr = np.maximum(hh - ll, np.maximum(
        np.abs(hh - pc), np.abs(ll - pc)))
    return float(tr.mean()) / _pip_of(sym)

def _trade_outcome(bars, sym, entry_s, side, dist_pips):
    """(exit_epoch, net25) for one candidate at a
    FIXED pip distance; exit/net are None while the
    trade is unresolved in the available bars and
    the 48h cap bar is not yet present. Locked
    replay form (SL-first in one bar)."""
    ts, _o, h, l, c = bars
    idx = int(np.searchsorted(ts, entry_s - 900))
    if idx >= len(ts) or ts[idx] != entry_s - 900:
        return None, None
    ph = h[idx + 1:idx + 1 + MAXHOLD_BARS]
    pl = l[idx + 1:idx + 1 + MAXHOLD_BARS]
    fwd = ts[idx + 1:idx + 1 + MAXHOLD_BARS]
    entry = float(c[idx])
    pip = _pip_of(sym)
    dist_price = dist_pips * pip
    if side > 0:
        sl_hit = pl <= entry - dist_price
        tp_hit = ph >= entry + dist_price
    else:
        sl_hit = ph >= entry + dist_price
        tp_hit = pl <= entry - dist_price
    isl = int(np.argmax(sl_hit)) if sl_hit.any() \
        else 10 ** 9
    itp = int(np.argmax(tp_hit)) if tp_hit.any() \
        else 10 ** 9
    if isl == 10 ** 9 and itp == 10 ** 9:
        if len(ph) >= MAXHOLD_BARS:
            gross = side * (float(c[idx + MAXHOLD_BARS])
                            - entry) / pip
            return entry_s + MAX_HOLD * 3600, \
                gross - COST_PIPS
        return None, None
    if isl <= itp:
        return int(fwd[isl]) + 900, -dist_pips - COST_PIPS
    return int(fwd[itp]) + 900, dist_pips - COST_PIPS


def _slot_rows(T, m15_bars):
    """Candidate rows for one slot: for every
    symbol with an available entry bar, both
    sides, each row carrying BOTH sources'
    score / in-band flag / distance / outcome.
    Canonical order: symbol index, side desc
    (BUY first)."""
    rows = []
    hour = (T % 86400) // 3600
    for sym in SYMBOLS:
        bars = m15_bars.get(sym)
        if bars is None:
            continue
        ts, _o, h, l, c = bars
        idx = int(np.searchsorted(ts, T - 900))
        if idx >= len(ts) or ts[idx] != T - 900 \
                or idx < 31:
            continue
        pos = _pos32(h, l, c, idx)
        if pos is None:
            continue
        entry_px = float(c[idx])
        atr = None
        per_src = {}
        for tag, eqset in (("W", EQUATIONS_W),
                           ("A", EQUATIONS_A)):
            eq = eqset[sym]
            lo, hi = BANDS[eq["band"]]
            if eq["step"] is not None:
                if atr is None:
                    atr = _atr14_pips(h, l, c, idx, sym)
                dist = eq["step"] * atr
            else:
                dist = float(eq["dist"])
            per_src[tag] = (eq, lo, hi, dist)
        for side in (1, -1):
            adj = pos if side > 0 else 1.0 - pos
            bucket = 0 if adj < BUCKET_E1 else \
                (1 if adj < BUCKET_E2 else 2)
            row = {"sym": sym, "side": side,
                   "entry_px": entry_px,
                   "pos_adj": float(adj),
                   "entry_s": int(T)}
            for tag, (eq, lo, hi, dist) in \
                    per_src.items():
                score = float(eq["cells"].get(
                    (hour, side, bucket), eq["prior"]))
                xp, net = _trade_outcome(
                    bars, sym, T, side, dist)
                row[f"score_{tag}"] = score
                row[f"in_band_{tag}"] = bool(
                    lo < adj < hi)
                row[f"dist_{tag}"] = dist
                row[f"exit_{tag}"] = xp
                row[f"net_{tag}"] = net
            rows.append(row)
    return rows


class FillState:
    """The U44-POOL union fill law in live form.
    Slots are processed in chronological order; a
    kept pick blocks its symbol (for BOTH
    sources) until its candle-replayed exit at
    the winning source's geometry; an unresolved
    pick blocks until resolved
    (resolve_pending)."""

    def __init__(self):
        self.max_exit = {}
        self.picks = []
        self.gov_firings = 0
        self.prot_refusals = 0
        self.year_counts = {}
        self.run_net = {}
        self.wdiv_redeals = 0
        self.ev = {e: {"slots_total": 0, "picks": 0,
                       "unfilled_no_rows": 0,
                       "unfilled_all_blocked": 0,
                       "tier2": 0, "tier3": 0}
                   for e in ("disc", "audit")}

    def to_dict(self):
        return {
            "max_exit": {k: ("inf" if v == float("inf")
                             else v)
                         for k, v in
                         self.max_exit.items()},
            "picks": self.picks,
            "prot_refusals": self.prot_refusals,
            "year_counts": {str(k): v for k, v in
                            self.year_counts.items()},
            "wdiv_redeals": self.wdiv_redeals,
            "run_net": {str(k): v for k, v in
                        self.run_net.items()}}

    def from_dict(self, d):
        self.max_exit = {k: (float("inf")
                             if v == "inf" else int(v))
                         for k, v in d.get(
                             "max_exit", {}).items()}
        self.picks = d.get("picks", [])
        self.prot_refusals = d.get(
            "prot_refusals", 0)
        self.year_counts = {int(k): list(v)
                            for k, v in d.get(
                                "year_counts", {}).items()}
        self.wdiv_redeals = d.get(
            "wdiv_redeals", 0)
        self.run_net = {int(k): float(v)
                        for k, v in d.get(
                            "run_net", {}).items()}

    def _record(self, row, ts, tier, tag):
        pick = {"sym": row["sym"], "entry_s": int(ts),
                "side": int(row["side"]),
                "dist": float(row[f"dist_{tag}"]),
                "entry_px": float(row["entry_px"]),
                "score": float(row[f"score_{tag}"]),
                "tier": int(tier),
                "layer": tag,
                "exit": row[f"exit_{tag}"],
                "net": row[f"net_{tag}"]}
        self.picks.append(pick)
        _yr = _dt.datetime.fromtimestamp(
            int(ts), _dt.timezone.utc).year
        _yc = self.year_counts.setdefault(
            _yr, [0, 0])
        _yc[0] += 1
        if pick["net"] > 0:
            _yc[1] += 1
        _wk = _dt.datetime.fromtimestamp(
            int(ts), _dt.timezone.utc).isocalendar()[1]
        self.run_net[_wk] = self.run_net.get(
            _wk, 0.0) + float(pick["net"])
        if row[f"exit_{tag}"] is None:
            self.max_exit[row["sym"]] = float("inf")
        else:
            self.max_exit[row["sym"]] = max(
                self.max_exit.get(row["sym"], -1),
                int(row[f"exit_{tag}"]))
        return pick

    def resolve_pending(self, m15_bars):
        for pick in self.picks:
            if pick["exit"] is not None:
                continue
            bars = m15_bars.get(pick["sym"])
            if bars is None:
                continue
            xp, net = _trade_outcome(
                bars, pick["sym"], pick["entry_s"],
                pick["side"], pick["dist"])
            if xp is None:
                continue
            pick["exit"] = int(xp)
            pick["net"] = float(net)
            ex = [p["exit"] if p["exit"] is not None
                  else float("inf")
                  for p in self.picks
                  if p["sym"] == pick["sym"]]
            self.max_exit[pick["sym"]] = max(ex)

    def process_slot(self, ts, era, rows):
        """The union fill law (win ranking, noisy-OR
        agreement): tier 1 = highest adjusted rank
        among firing offers; tier 2 = largest
        adjusted margin among in-band offers;
        tier 3 = largest own margin among any-band
        offers. Ties: higher own score, SRC-W
        before SRC-A, lower symbol index, BUY
        first. Returns picked row indices (<= 1)
        and stamps the winning source's fields
        onto the picked row."""
        e = self.ev[era]
        e["slots_total"] += 1
        if not rows:
            e["unfilled_no_rows"] += 1
            return []
        by_sym = {}
        for i, r in enumerate(rows):
            if self.max_exit.get(r["sym"], -1) > ts:
                continue
            by_sym.setdefault(r["sym"], []).append(i)
        if not by_sym:
            e["unfilled_all_blocked"] += 1
            return []
        eqsets = {"W": EQUATIONS_W, "A": EQUATIONS_A}

        def best(idxs, keyf):
            return min(idxs, key=lambda i: (
                -keyf(rows[i]), SYM_IDX[rows[i]["sym"]],
                0 if rows[i]["side"] > 0 else 1))

        # per (source, symbol): best in-band row,
        # best any-band row (own margin)
        bb, ba = {}, {}
        for tag in ("W", "A"):
            for sym, idxs in by_sym.items():
                tau = eqsets[tag][sym]["tau"]
                br = [i for i in idxs
                      if rows[i][f"in_band_{tag}"]]
                if br:
                    bb[(tag, sym)] = best(
                        br, lambda r: r[f"score_{tag}"])
                ba[(tag, sym)] = best(
                    idxs, lambda r: r[f"score_{tag}"]
                    - tau)
        agree = {}
        for sym in by_sym:
            if ("W", sym) in bb and ("A", sym) in bb \
                    and bb[("W", sym)] == bb[("A", sym)]:
                agree[sym] = bb[("W", sym)]

        def _select(bb_, ba_, agree_):
            def adj_rank(tag, sym):
                i = bb_[(tag, sym)]
                if agree_.get(sym) == i:
                    pw = rows[i]["score_W"]
                    pa = rows[i]["score_A"]
                    return 1.0 - (1.0 - pw) * (1.0 - pa)
                return rows[i][f"score_{tag}"]

            def primary_val(tag, sym, tier):
                if tier == 1:
                    return adj_rank(tag, sym)
                if tier == 2:
                    return adj_rank(tag, sym) \
                        - eqsets[tag][sym]["tau"]
                i = ba_[(tag, sym)]
                return rows[i][f"score_{tag}"] \
                    - eqsets[tag][sym]["tau"]

            def offer_key(tag, sym, tier):
                i = bb_[(tag, sym)] if tier != 3 \
                    else ba_[(tag, sym)]
                return (-primary_val(tag, sym, tier),
                        -rows[i][f"score_{tag}"],
                        0 if tag == "W" else 1,
                        SYM_IDX[sym],
                        0 if rows[i]["side"] > 0 else 1)

            firing = [(tag, sym) for (tag, sym) in bb_
                      if rows[bb_[(tag, sym)]]
                      [f"score_{tag}"]
                      >= eqsets[tag][sym]["tau"]]
            if firing:
                tag, sym = min(
                    firing,
                    key=lambda ts_: offer_key(
                        ts_[0], ts_[1], 1))
                return tag, sym, 1, bb_[(tag, sym)]
            if bb_:
                tag, sym = min(
                    bb_.keys(),
                    key=lambda ts_: offer_key(
                        ts_[0], ts_[1], 2))
                return tag, sym, 2, bb_[(tag, sym)]
            tag, sym = min(
                ba_.keys(),
                key=lambda ts_: offer_key(
                    ts_[0], ts_[1], 3))
            return tag, sym, 3, ba_[(tag, sym)]


        def _select_wdiv(bb_, ba_, agree_):
            # R4-040 WDIV layer: same tiers and keys
            # as _select; inside the tier, minimise
            # (overlap, offer_key).
            def adj_rank(tag, sym):
                i = bb_[(tag, sym)]
                if agree_.get(sym) == i:
                    pw = rows[i]["score_W"]
                    pa = rows[i]["score_A"]
                    return 1.0 - (1.0 - pw) * (1.0 - pa)
                return rows[i][f"score_{tag}"]

            def primary_val(tag, sym, tier):
                if tier == 1:
                    return adj_rank(tag, sym)
                if tier == 2:
                    return adj_rank(tag, sym) \
                        - eqsets[tag][sym]["tau"]
                i = ba_[(tag, sym)]
                return rows[i][f"score_{tag}"] \
                    - eqsets[tag][sym]["tau"]

            def offer_key(tag, sym, tier):
                i = bb_[(tag, sym)] if tier != 3 \
                    else ba_[(tag, sym)]
                return (-primary_val(tag, sym, tier),
                        -rows[i][f"score_{tag}"],
                        0 if tag == "W" else 1,
                        SYM_IDX[sym],
                        0 if rows[i]["side"] > 0 else 1)

            def _overlap(tag, sym, tier):
                i = bb_[(tag, sym)] if tier != 3 \
                    else ba_[(tag, sym)]
                adj = rows[i]["pos_adj"]
                bucket = 0 if adj < BUCKET_E1 else \
                    (1 if adj < BUCKET_E2 else 2)
                cell = (SYM_IDX[sym],
                        (int(ts) % 86400) // 3600,
                        rows[i]["side"], bucket)
                lw = WDIV_LW.get(cell)
                if not lw:
                    return 0
                losing = {w for w, v in
                          self.run_net.items() if v < 0}
                return len(set(lw) & losing)

            firing = [(tag, sym) for (tag, sym) in bb_
                      if rows[bb_[(tag, sym)]]
                      [f"score_{tag}"]
                      >= eqsets[tag][sym]["tau"]]
            if firing:
                tag, sym = min(
                    firing,
                    key=lambda ts_: (
                        _overlap(ts_[0], ts_[1], 1),
                        offer_key(ts_[0], ts_[1], 1)))
                return tag, sym, 1, bb_[(tag, sym)]
            if bb_:
                tag, sym = min(
                    bb_.keys(),
                    key=lambda ts_: (
                        _overlap(ts_[0], ts_[1], 2),
                        offer_key(ts_[0], ts_[1], 2)))
                return tag, sym, 2, bb_[(tag, sym)]
            tag, sym = min(
                ba_.keys(),
                key=lambda ts_: (
                    _overlap(ts_[0], ts_[1], 3),
                    offer_key(ts_[0], ts_[1], 3)))
            return tag, sym, 3, ba_[(tag, sym)]

        _plain = _select(bb, ba, agree)
        tag, sym, tier, pick = _select_wdiv(bb, ba, agree)
        if pick != _plain[3]:
            self.wdiv_redeals += 1
        # --- R4-018 governor: causal realised-path
        # step-aside (GOV-2). State S(T) = sum of nets
        # of the last 5 exited picks (exit <= ts,
        # ordered by (exit, pick order)); a symbol is
        # clean iff the sum of its own last 3 exited
        # nets is >= 0 (0.0 if none). On firing, the
        # winner's symbol is removed and the pick is
        # re-made among clean symbols only; if none
        # is clean, the governor abstains (winner
        # taken unchanged).
        exited = [p for p in self.picks
                  if p["exit"] is not None
                  and p["exit"] <= ts]
        if exited:
            exited.sort(key=lambda p: p["exit"])
            state = sum(p["net"] for p in exited[-5:])
            if state <= GOV_THETA:
                rest = [s2 for s2 in by_sym if s2 != sym]
                clean = []
                for s2 in rest:
                    own = [p for p in exited
                           if p["sym"] == s2]
                    osum = sum(p["net"]
                               for p in own[-3:]) \
                        if own else 0.0
                    if osum >= 0:
                        clean.append(s2)
                bb2 = {k: v for k, v in bb.items()
                       if k[1] in clean}
                ba2 = {k: v for k, v in ba.items()
                       if k[1] in clean}
                if bb2 or ba2:
                    agree2 = {s2: i2 for s2, i2
                              in agree.items()
                              if s2 in clean}
                    wtag, wsym, wtier, wpick = \
                        tag, sym, tier, pick
                    tag, sym, tier, pick = _select(
                        bb2, ba2, agree2)
                    # --- R4-029 clause P: at a protected
                    # slot (the pick year's running win rate
                    # over committed picks at or below
                    # PROT_T), refuse the step-aside when
                    # the replacement would dilute the
                    # year's running rate versus keeping
                    # the union winner.
                    _yr = _dt.datetime.fromtimestamp(
                        int(ts), _dt.timezone.utc).year
                    _yc = self.year_counts.get(_yr)
                    _refuse = False
                    if _yc is not None and _yc[0] >= 1 \
                            and _yc[1] / _yc[0] <= PROT_T:
                        _wn = rows[wpick][
                            f"net_{wtag}"]
                        _rn = rows[pick][
                            f"net_{tag}"]
                        if (_yc[1] + (1 if _rn > 0
                                      else 0)) \
                                / (_yc[0] + 1) \
                                < (_yc[1] + (1 if _wn > 0
                                             else 0)) \
                                / (_yc[0] + 1) - 1e-12:
                            _refuse = True
                    if _refuse:
                        tag, sym, tier, pick = \
                            wtag, wsym, wtier, wpick
                        self.prot_refusals += 1
                    else:
                        self.gov_firings += 1
        if tier == 2:
            e["tier2"] += 1
        elif tier == 3:
            e["tier3"] += 1
        row = rows[pick]
        row["dist"] = row[f"dist_{tag}"]
        row["exit"] = row[f"exit_{tag}"]
        row["net"] = row[f"net_{tag}"]
        row["score"] = row[f"score_{tag}"]
        row["src"] = tag
        e["picks"] += 1
        self._record(row, ts, tier, tag)
        return [pick]


