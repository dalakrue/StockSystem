def _pip_of(sym):
    return 0.01 if "JPY" in sym else 0.0001


def _atr14(h, l, c, idx):
    """Mean true range over bars idx-13..idx (prev
    closes idx-14..idx-1), in price units; None if
    unavailable."""
    if idx < 14:
        return None
    hh = h[idx - 13:idx + 1]
    ll = l[idx - 13:idx + 1]
    pc = c[idx - 14:idx]
    tr = np.maximum(hh - ll, np.maximum(np.abs(hh - pc),
                                        np.abs(ll - pc)))
    v = float(tr.mean())
    return v if v > 0 else None


def _pos32(h, l, c, idx):
    """Close position in the last-32-M15-bar range
    [0, 1] -- the round's pos32 feature verbatim:
    (entry close - lowest low of bars idx-31..idx)
    / (highest high - lowest low of the same bars);
    None when the window is unavailable (idx < 31)
    or the range is flat."""
    if idx < 31:
        return None
    hh = float(np.max(h[idx - 31:idx + 1]))
    ll = float(np.min(l[idx - 31:idx + 1]))
    if hh <= ll:
        return None
    return (float(c[idx]) - ll) / (hh - ll)


def _trade_outcome(bars, sym, entry_s, side, dist_price,
                   mult, atr_pips):
    """(exit_epoch, net25) for one candidate from the
    symbol's M15 bar arrays (ts, o, h, l, c); exit/net
    are None while the trade is unresolved in the
    available bars and the 48h cap bar is not yet
    present. (cycle93ad's machinery, verbatim.)"""
    ts, _o, h, l, c = bars
    idx = int(np.searchsorted(ts, entry_s - 900))
    if idx >= len(ts) or ts[idx] != entry_s - 900:
        return None, None
    ph = h[idx + 1:idx + 1 + MAXHOLD_BARS]
    pl = l[idx + 1:idx + 1 + MAXHOLD_BARS]
    fwd = ts[idx + 1:idx + 1 + MAXHOLD_BARS]
    entry = float(c[idx])
    pip = _pip_of(sym)
    if len(ph) >= MAXHOLD_BARS:
        # full path available: exact filed replay
        if side > 0:
            sl_hit = pl <= entry - dist_price
            tp_hit = ph >= entry + dist_price
        else:
            sl_hit = ph >= entry + dist_price
            tp_hit = pl <= entry - dist_price
        isl = int(np.argmax(sl_hit)) if sl_hit.any() \
            else 10 ** 9
        itp = int(np.argmax(tp_hit)) if tp_hit.any() \
            else 10 ** 9
        if isl == 10 ** 9 and itp == 10 ** 9:
            gross = side * (float(c[idx + MAXHOLD_BARS])
                            - entry) / pip
            return entry_s + MAX_HOLD * 3600, \
                gross - COST_PIPS
        if isl <= itp:
            return int(fwd[isl]) + 900, -mult * atr_pips \
                - COST_PIPS
        return int(fwd[itp]) + 900, mult * atr_pips \
            - COST_PIPS
    # partial path (live): resolve only on an actual hit
    if side > 0:
        sl_hit = pl <= entry - dist_price
        tp_hit = ph >= entry + dist_price
    else:
        sl_hit = ph >= entry + dist_price
        tp_hit = pl <= entry - dist_price
    isl = int(np.argmax(sl_hit)) if sl_hit.any() else 10 ** 9
    itp = int(np.argmax(tp_hit)) if tp_hit.any() else 10 ** 9
    if isl == 10 ** 9 and itp == 10 ** 9:
        return None, None
    if isl <= itp:
        return int(fwd[isl]) + 900, -mult * atr_pips \
            - COST_PIPS
    return int(fwd[itp]) + 900, mult * atr_pips - COST_PIPS


def _slot_rows(T, m15_bars):
    """Candidate rows for one slot, in canonical order
    (symbol index, side desc, step asc -- one step) --
    the B40 population restricted to the slot, step
    2.0 only. Each row: sym, side, mult, code (the
    winXband cell code), score (the cell's shrunk
    DISC P(win); the prior for a cell outside the
    shipped table), entry_px, atr (pips), exit, net
    (exit/net None while unresolved in the available
    bars), pos_adj (the side-adjusted band position,
    for the record). A symbol contributes rows only
    when its M15 entry bar (the bar ending at T),
    the 14-bar ATR window and the 32-bar range
    window are available, and the side-adjusted
    position lies strictly inside the band."""
    rows = []
    hour = (T % 86400) // 3600
    for sym in SYMBOLS:
        bars = m15_bars.get(sym)
        if bars is None:
            continue
        ts, _o, h, l, c = bars
        idx = int(np.searchsorted(ts, T - 900))
        if idx >= len(ts) or ts[idx] != T - 900 \
                or idx < 31:
            continue
        pip = _pip_of(sym)
        atr_price = _atr14(h, l, c, idx)
        if atr_price is None:
            continue
        pos = _pos32(h, l, c, idx)
        if pos is None:
            continue
        atr = float(atr_price / pip)
        entry_px = float(c[idx])
        sidx = SYM_IDX[sym]
        for side in (1, -1):
            adj = pos if side > 0 else 1.0 - pos
            if not (BAND_LO < adj < BAND_HI):
                continue
            bucket = 0 if adj < BUCKET_E1 else \
                (1 if adj < BUCKET_E2 else 2)
            # the round's code convention (work/tab5.py
            # codes): side01 = 1 for BUY, 0 for SELL --
            # NOT the CELL_EXP convention of cycle93ad
            side01 = 1 if side > 0 else 0
            code = (((sidx * 24 + hour) * 2 + side01) * 7
                    + MULT_IDX_20) * 3 + bucket
            dist = STEP * atr * pip
            xp, net = _trade_outcome(
                bars, sym, T, side, dist, STEP, atr)
            rows.append({
                "sym": sym, "side": side, "mult": STEP,
                "code": int(code),
                "score": float(WIN_TABLE.get(int(code),
                                             WIN_PRIOR)),
                "entry_px": entry_px, "atr": atr,
                "pos_adj": float(adj),
                "exit": xp, "net": net,
                "entry_s": int(T)})
    return rows


class FillState:
    """The B40__S20__winXband fill in live form. Slots
    are processed in chronological order. A kept pick
    blocks its symbol until its candle-replayed exit;
    a pick whose exit is not yet resolvable from the
    available bars blocks its symbol until resolved
    (resolve_pending) -- the live form of the filed
    1-open-per-symbol ledger."""

    def __init__(self):
        self.max_exit = {}
        self.picks = []
        self.ev = {e: {"slots_total": 0, "picks": 0,
                       "unfilled_no_rows": 0,
                       "unfilled_all_blocked": 0}
                   for e in ("disc", "audit")}

    # -- persistence -------------------------------------------------
    def to_dict(self):
        return {
            "max_exit": {k: ("inf" if v == float("inf")
                             else v)
                         for k, v in self.max_exit.items()},
            "picks": self.picks}

    def from_dict(self, d):
        self.max_exit = {k: (float("inf") if v == "inf"
                             else int(v))
                         for k, v in d.get("max_exit",
                                           {}).items()}
        self.picks = d.get("picks", [])

    # -- core ----------------------------------------------------------
    def _record(self, row, ts):
        pick = {"sym": row["sym"], "entry_s": int(ts),
                "side": int(row["side"]),
                "mult": float(row["mult"]),
                "entry_px": float(row["entry_px"]),
                "atr": float(row["atr"]),
                "score": float(row["score"]),
                "code": int(row["code"]),
                "layer": "win",
                "exit": row["exit"], "net": row["net"]}
        self.picks.append(pick)
        if row["exit"] is None:
            self.max_exit[row["sym"]] = float("inf")
        else:
            self.max_exit[row["sym"]] = max(
                self.max_exit.get(row["sym"], -1),
                int(row["exit"]))
        return pick

    def resolve_pending(self, m15_bars):
        """Recompute unresolved picks from the bars now
        available; on resolution the pick's true exit
        replaces the blocking placeholder."""
        for pick in self.picks:
            if pick["exit"] is not None:
                continue
            bars = m15_bars.get(pick["sym"])
            if bars is None:
                continue
            dist = pick["mult"] * pick["atr"] \
                * _pip_of(pick["sym"])
            xp, net = _trade_outcome(
                bars, pick["sym"], pick["entry_s"],
                pick["side"], dist, pick["mult"],
                pick["atr"])
            if xp is None:
                continue
            pick["exit"] = int(xp)
            pick["net"] = float(net)
            ex = [p["exit"] if p["exit"] is not None
                  else float("inf")
                  for p in self.picks
                  if p["sym"] == pick["sym"]]
            self.max_exit[pick["sym"]] = max(ex)

    def process_slot(self, ts, era, rows):
        """rows: the slot's candidate rows in canonical
        order (see _slot_rows). Returns the picked row
        index list (at most one): the highest shrunk
        P(win) first, canonical order on ties, first
        unblocked candidate wins -- the round's fill
        (stream2.fill with the design's lam-weighted
        winXband score)."""
        e = self.ev[era]
        e["slots_total"] += 1
        if not rows:
            e["unfilled_no_rows"] += 1
            return []
        order = sorted(
            range(len(rows)),
            key=lambda p: (-rows[p]["score"], p))
        for p in order:
            if self.max_exit.get(rows[p]["sym"], -1) > ts:
                continue
            e["picks"] += 1
            self._record(rows[p], ts)
            return [p]
        e["unfilled_all_blocked"] += 1
        return []


